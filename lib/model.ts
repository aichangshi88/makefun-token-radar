// Token Radar, model radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every rankable pre-token protocol in the snapshot: the 40 on the watchlist (the
// floor, never a ceiling) plus every other pre-token protocol below the floor that is not an exchange
// and not a versioned pool of another protocol. Live-token protocols are kept apart and shown with the
// market's own values, never mixed into the ranked board.
//
// Implied value is calibrated from the snapshot itself, not from a flat house multiple:
//
//   category multiple = the median market-cap-per-TVL of the protocols in the same category whose
//                         token already trades (three or more of them; the global median otherwise),
//                         clamped to [0.05, 1.5]. A lending protocol is worth a different share of
//                         its TVL than a bridge, and the snapshot says by how much.
//   base       = tvl_usd x category multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.7 + min(age_days, 1095) / 1095 x 0.3   (age_days unknown: 365)
//   chainsMult = 1 + 0.02 x min(chains - 1, 10), at least 1
//   implied    = max(1, round(base x growthMult x maturity x chainsMult))
//
// No protocol name is ever special-cased: the same function scores every row, and the dashboard
// prints the calibration table so a reader can check the multiples against the snapshot.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

